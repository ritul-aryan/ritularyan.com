// Generates src/styles/tokens.css from the prototype's THEMES object, so the
// token values are extracted rather than transcribed.
//
//   node scripts/gen-tokens.mjs [path/to/deploy/index.html]

import { readFileSync, writeFileSync } from 'node:fs';

const SRC = process.argv[2] ?? '/mnt/user-data/uploads/portfolio/deploy/index.html';
const OUT = new URL('../src/styles/tokens.css', import.meta.url);

const html = readFileSync(SRC, 'utf8');
const start = html.indexOf('const THEMES = {');
if (start === -1) throw new Error('THEMES not found');
const open = html.indexOf('{', start);
let depth = 0,
  end = -1;
for (let i = open; i < html.length; i++) {
  if (html[i] === '{') depth++;
  else if (html[i] === '}' && --depth === 0) {
    end = i + 1;
    break;
  }
}
const THEMES = eval('(' + html.slice(open, end) + ')');

const keys = Object.keys(THEMES.dark);
const lightKeys = Object.keys(THEMES.light);
if (keys.join() !== lightKeys.join()) throw new Error('theme key mismatch');

const vars = (t) => keys.map((k) => `  --rk-${k}: ${t[k]};`).join('\n');

const css = `/* AUTO-GENERATED by scripts/gen-tokens.mjs. Do not hand-edit.
 *
 * Extracted verbatim from the THEMES object in deploy/index.html. The prototype
 * set these on document.documentElement from JS; here they are real CSS, so the
 * static shell is correctly themed with no script running.
 *
 * ${keys.length} tokens per theme. Dark is the default; light is opt-in via
 * [data-theme='light'] on <html>, which is all ThemeToggle needs to flip.
 */

:root {
${vars(THEMES.dark)}

  /* Type stacks. Self-hosted via @fontsource — no requests to Google. */
  --rk-font-sans: 'IBM Plex Sans', system-ui, sans-serif;

  /*
   * Approved deviation 3: Tiro Devanagari Hindi sits after IBM Plex Mono as the
   * Devanagari fallback. IBM Plex Mono ships no Devanagari glyphs, so the
   * footer index links ("00 · परिचय / About") would otherwise fall back to
   * whatever the visitor's OS provides — or render as tofu on a machine with no
   * Devanagari font at all. Plex Mono still wins for Latin; Tiro is only reached
   * for codepoints Plex Mono cannot draw. Do NOT widen this to any other stack.
   */
  --rk-font-mono: 'IBM Plex Mono', 'Tiro Devanagari Hindi', monospace;
  --rk-font-display: 'Bricolage Grotesque Variable', sans-serif;
  --rk-font-serif-dev: 'Rozha One', serif;
  --rk-font-dev: 'Tiro Devanagari Hindi', serif;

  /* Fixed header height. The hero subtracts this from the viewport. */
  --rk-bar-h: 52px;
}

:root[data-theme='light'] {
${vars(THEMES.light)}
}

/*
 * NOTE: deliberately no prefers-color-scheme block. The prototype defaults to
 * dark unconditionally and reads only localStorage:
 *   const theme = st === "light" || st === "dark" ? st : (props.defaultTheme || "dark")
 * Honouring the OS preference would be a deviation. Do not add one.
 */
`;

writeFileSync(OUT, css);
console.log(`wrote tokens.css — ${keys.length} tokens x 2 themes`);
console.log('dark :', keys.map((k) => `${k}=${THEMES.dark[k]}`).join('  '));
console.log('light:', keys.map((k) => `${k}=${THEMES.light[k]}`).join('  '));
